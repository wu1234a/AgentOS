using AgentOS.Domain.Skills;

namespace AgentOS.Application.Skills;

public sealed record SkillView(
    Guid Id,
    Guid? ProjectId,
    string? ProjectSlug,
    string Code,
    string Version,
    string RelativePath,
    string? ContentHash,
    string? Description,
    bool IsEnabled,
    DateTime CreatedAtUtc,
    DateTime UpdatedAtUtc);

public sealed class CreateSkillRequest
{
    public Guid? ProjectId { get; init; }

    public string? Code { get; init; }

    public string? Version { get; init; }

    public string? Description { get; init; }

    public string? Content { get; init; }
}

public sealed class UpdateSkillRequest
{
    public string? Description { get; init; }
}

public enum SkillOutcome
{
    Ok = 0,
    NotFound = 1,
    Conflict = 2,
    ValidationFailed = 3,
    StorageUnavailable = 4
}

public sealed record SkillResult(
    SkillOutcome Outcome,
    SkillView? Skill,
    string? ErrorCode,
    IReadOnlyDictionary<string, string[]> Errors)
{
    public static SkillResult Ok(SkillView skill) => new(SkillOutcome.Ok, skill, null, Empty);

    public static SkillResult NotFound() => new(SkillOutcome.NotFound, null, "skill-not-found", Empty);

    public static SkillResult Conflict(string code) => new(SkillOutcome.Conflict, null, code, Empty);

    public static SkillResult Invalid(IReadOnlyDictionary<string, string[]> errors)
        => new(SkillOutcome.ValidationFailed, null, "skill-invalid", errors);

    public static SkillResult StorageUnavailable()
        => new(SkillOutcome.StorageUnavailable, null, "skill-storage-unavailable", Empty);

    private static readonly Dictionary<string, string[]> Empty = [];
}

public sealed record StoredSkillContent(string RelativePath, string ContentHash);

/// <summary>Stores skill markdown; the relative path is always generated by the server.</summary>
public interface ISkillStore
{
    bool IsConfigured { get; }

    Task<StoredSkillContent> SaveAsync(
        Guid? projectId,
        string code,
        string version,
        string content,
        CancellationToken cancellationToken);

    Task<string?> ReadAsync(string relativePath, CancellationToken cancellationToken);

    Task DeleteAsync(string relativePath, CancellationToken cancellationToken);
}

public interface ISkillRepository
{
    Task<(IReadOnlyList<SkillView> Items, int Total)> ListAsync(
        Guid? projectId,
        string? code,
        bool includeDisabled,
        int limit,
        int offset,
        CancellationToken cancellationToken);

    Task<Skill?> GetTrackedAsync(Guid skillId, CancellationToken cancellationToken);

    Task<SkillView?> GetViewAsync(Guid skillId, CancellationToken cancellationToken);

    Task<bool> VersionExistsAsync(
        Guid? projectId,
        string code,
        string version,
        CancellationToken cancellationToken);

    Task<bool> TryAddAsync(Skill skill, CancellationToken cancellationToken);

    Task SaveAsync(CancellationToken cancellationToken);
}
